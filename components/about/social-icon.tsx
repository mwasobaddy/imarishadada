export function SocialIcon({
  platform,
  className = "h-4 w-4",
}: {
  platform: SocialKey;
  className?: string;
}) {
  const LucideGlyph = LUCIDE[platform];
  if (LucideGlyph) return <LucideGlyph className={className} aria-hidden="true" />;

  const path = BRAND_PATHS[platform];
  if (path) {
    return (
      <svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" className={className}>
        <path d={path} />
      </svg>
    );
  }

  // A platform the database allows but this file does not know about. Render a
  // globe rather than nothing, so the link is still reachable.
  return <Globe className={className} aria-hidden="true" />;
}

/** Turn a stored value into an href. `email` is a bare address, not a URL. */
export function socialHref(platform: SocialKey, value: string): string {
  if (platform === "email") {
    return value.startsWith("mailto:") ? value : `mailto:${value}`;
  }
  return value.startsWith("http") ? value : `https://${value}`;
}
